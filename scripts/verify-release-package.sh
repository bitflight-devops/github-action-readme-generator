#!/usr/bin/env bash
set -euo pipefail

# This private workspace represents a public npm consumer, not the publisher.
unset GITHUB_ACTIONS GITHUB_REPOSITORY GITHUB_TOKEN GH_TOKEN NPM_TOKEN NODE_AUTH_TOKEN \
  ACTIONS_ID_TOKEN_REQUEST_TOKEN ACTIONS_ID_TOKEN_REQUEST_URL

expected_version=${1:?expected release version}
scratch=$(mktemp -d)
trap 'rm -rf -- "$scratch"' EXIT

tarball=$(npm pack --ignore-scripts --pack-destination "$scratch" --silent)
for runtime in "$(command -v node)" "${RELEASE_COMPAT_NODE:?path to minimum supported Node}"; do (
  export PATH="$(dirname "$runtime"):$PATH"
  test "$(command -v node)" = "$runtime"
  echo "Verifying package $expected_version on $("$runtime" --version)"
  cd "$(mktemp -d "$scratch/consumer.XXXXXX")"
  printf '%s\n' '{"name":"release-smoke","version":"0.0.0","private":true}' >package.json
  npm install --engine-strict --ignore-scripts --no-audit --no-fund "$scratch/$tarball"
  node -e 'const manifest = require("./node_modules/github-action-readme-generator/package.json"); if (manifest.version !== process.argv[1]) throw new Error(`Expected ${process.argv[1]}, packed ${manifest.version}`);' "$expected_version"

  cat >action.yml <<'YAML'
name: Release smoke
description: Generated by the packaged CLI
runs:
  using: node24
  main: index.js
YAML
  cat >README.md <<'MARKDOWN'
# Consumer-owned heading

<!-- start description -->
<!-- end description -->
MARKDOWN
  cat >.ghadocs.json <<'JSON'
{
  "owner": "testowner",
  "repo": "testrepo",
  "paths": { "action": "action.yml", "readme": "README.md" },
  "sections": ["description"]
}
JSON

  ./node_modules/.bin/github-action-readme-generator
  grep -Fxq '# Consumer-owned heading' README.md
  grep -Fxq 'Generated by the packaged CLI' README.md
  "$runtime" --input-type=module -e "import { generateReadme } from 'github-action-readme-generator'; if (typeof generateReadme !== 'function') process.exit(1)"
); done
